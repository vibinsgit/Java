public class Core1 {
    public static void main(String[] args) {
 
        int num1 = 0b101;
        System.out.println("num1 : " + num1);

        // Hexa Decimal Number
        int num2 = 0x7E;
        System.out.println("num2 : " + num2);

        int num3 = 10_00_00_00;
        System.out.println("num2 : " + num3);

        char a = 'c';
        System.out.println("a : " + a);

        a++;
        System.out.println("a++ : " + a);
    }
}